"""Turns docs/legal/*.md into src/content/legal.ts for the in-app Terms & Privacy screen.
Usage: python3 scripts/build-legal.py"""
import json, re

def blocks(md):
    out = []
    for line in md.splitlines():
        s = line.strip()
        if not s or s.startswith('|---'):
            continue
        s = re.sub(r'\*\*(.+?)\*\*', r'\1', s)
        if s.startswith('# '):
            out.append({'t': 'title', 'x': s[2:]})
        elif s.startswith('## '):
            out.append({'t': 'h', 'x': s[3:]})
        elif s.startswith('- '):
            out.append({'t': 'li', 'x': s[2:]})
        elif s.startswith('|'):
            cells = [c.strip() for c in s.strip('|').split('|')]
            if cells[0] == 'What':
                continue
            out.append({'t': 'li', 'x': f"{cells[0]}: {cells[1].lower()}. Seen by: {cells[2]}"})
        elif s.startswith('_') and s.endswith('_'):
            out.append({'t': 'note', 'x': s.strip('_')})
        else:
            out.append({'t': 'p', 'x': s})
    return out

data = {k: blocks(open(f'docs/legal/{k.upper()}.md').read()) for k in ('terms', 'privacy')}
src = '// Generated by scripts/build-legal.py from docs/legal/*.md. Edit the markdown, then rerun.\n'
src += 'export type LegalBlock = { t: "title" | "h" | "p" | "li" | "note"; x: string };\n'
src += 'export const LEGAL: Record<"terms" | "privacy", LegalBlock[]> = ' + json.dumps(data, indent=1, ensure_ascii=False) + ';\n'
open('src/content/legal.ts', 'w').write(src)
print('ok', {k: len(v) for k, v in data.items()})
